"""Measure the analytical queries before and after creating the secondary indexes.

    python scripts/benchmark_queries.py [--runs 5]

Steps: drop the indexes in sql/indexes.sql, VACUUM ANALYZE, run every query in
sql/analytical_queries.sql with EXPLAIN ANALYZE, create the indexes, VACUUM ANALYZE, run again.
Prints a comparison table and writes docs/query_performance.md. The indexes are left in place.
"""

from __future__ import annotations

import argparse
import json
import re
import statistics
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import psycopg2

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from etl.config import ROOT, load_settings  # noqa: E402

QUERIES_PATH = ROOT / "sql" / "analytical_queries.sql"
INDEXES_PATH = ROOT / "sql" / "indexes.sql"
REPORT_PATH = ROOT / "docs" / "query_performance.md"

SCAN_NODES = ("Index Only Scan", "Index Scan", "Bitmap Index Scan", "Seq Scan")


@dataclass
class Measurement:
    median_ms: float
    scans: list[str]
    shared_buffers: int
    plan_text: str


def load_queries(path: Path) -> dict[str, str]:
    """Split the file on '-- name: <id>' markers."""
    parts = re.split(r"^-- name:\s*(\w+)\s*$", path.read_text(encoding="utf-8"), flags=re.MULTILINE)
    return {name: body.strip().rstrip(";") for name, body in zip(parts[1::2], parts[2::2])}


def index_names(path: Path) -> list[str]:
    return re.findall(r"CREATE INDEX IF NOT EXISTS (\w+)", path.read_text(encoding="utf-8"))


def scans_on_bookings(plan: dict) -> list[str]:
    """Access methods used to read the bookings table, e.g. ['Index Only Scan (idx_...)']."""
    found = []
    node_type = plan.get("Node Type", "")
    if node_type in SCAN_NODES and (plan.get("Relation Name") == "bookings" or "idx_bookings" in plan.get("Index Name", "")):
        found.append(f"{node_type} ({plan['Index Name']})" if "Index Name" in plan else node_type)
    for child in plan.get("Plans", []):
        found.extend(scans_on_bookings(child))
    return found


def measure(cur, sql_text: str, runs: int) -> Measurement:
    cur.execute(sql_text)  # warm-up so every run reads from shared buffers
    timings, last = [], None
    for _ in range(runs):
        # TIMING OFF drops per-node clock calls, whose overhead would otherwise inflate both sides.
        cur.execute(f"EXPLAIN (ANALYZE, BUFFERS, TIMING OFF, FORMAT JSON) {sql_text}")
        last = cur.fetchone()[0][0]
        timings.append(last["Execution Time"])
    cur.execute(f"EXPLAIN (ANALYZE, BUFFERS, COSTS OFF, TIMING OFF) {sql_text}")
    plan_text = "\n".join(row[0] for row in cur.fetchall())
    top = last["Plan"]
    return Measurement(
        median_ms=statistics.median(timings),
        scans=scans_on_bookings(top) or ["(none)"],
        shared_buffers=top.get("Shared Hit Blocks", 0) + top.get("Shared Read Blocks", 0),
        plan_text=plan_text,
    )


def run_all(cur, queries: dict[str, str], runs: int) -> dict[str, Measurement]:
    cur.execute("VACUUM ANALYZE bookings")
    return {name: measure(cur, sql_text, runs) for name, sql_text in queries.items()}


def index_sizes(cur, names: list[str]) -> dict[str, str]:
    cur.execute(
        """
        SELECT c.relname, pg_size_pretty(pg_relation_size(c.oid))
        FROM pg_class c WHERE c.relkind = 'i' AND c.relname = ANY(%s)
        """,
        (names,),
    )
    sizes = dict(cur.fetchall())
    cur.execute("SELECT pg_size_pretty(pg_relation_size('bookings'))")
    sizes["bookings (table)"] = cur.fetchone()[0]
    return sizes


def results_table(before: dict[str, Measurement], after: dict[str, Measurement]) -> list[str]:
    lines = [
        "| Query | Before (ms) | After (ms) | Speed-up | Buffers before -> after | Plan before | Plan after |",
        "|---|---:|---:|---:|---:|---|---|",
    ]
    for name in before:
        b, a = before[name], after[name]
        speedup = b.median_ms / a.median_ms if a.median_ms else float("inf")
        lines.append(
            f"| `{name}` | {b.median_ms:.2f} | {a.median_ms:.2f} | {speedup:.1f}x "
            f"| {b.shared_buffers:,} -> {a.shared_buffers:,} | {', '.join(b.scans)} | {', '.join(a.scans)} |"
        )
    return lines


def write_report(
    before: dict[str, Measurement],
    after: dict[str, Measurement],
    sizes: dict[str, str],
    queries: dict[str, str],
    runs: int,
    server_version: str,
    row_count: int,
) -> None:
    lines = [
        "# Query performance: before and after indexing",
        "",
        f"Generated by `python scripts/benchmark_queries.py` on {datetime.now():%Y-%m-%d %H:%M}.",
        f"{server_version.split(',')[0]}, {row_count:,} rows in `bookings`. Times are the median "
        f"`Execution Time` of {runs} `EXPLAIN ANALYZE` runs after a warm-up run (warm cache); "
        "buffers are 8 kB pages read from shared memory or disk.",
        "",
        *results_table(before, after),
        "",
        "## Index sizes",
        "",
        "| Relation | Size |",
        "|---|---:|",
        *[f"| `{name}` | {size} |" for name, size in sizes.items()],
        "",
        "## Query plans",
        "",
    ]
    for name, sql_text in queries.items():
        lines += [
            f"### `{name}`",
            "",
            "```sql",
            sql_text + ";",
            "```",
            "",
            "<details><summary>Plan before indexing</summary>",
            "",
            "```",
            before[name].plan_text,
            "```",
            "",
            "</details>",
            "",
            "<details><summary>Plan after indexing</summary>",
            "",
            "```",
            after[name].plan_text,
            "```",
            "",
            "</details>",
            "",
        ]
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs", type=int, default=5, help="EXPLAIN ANALYZE runs per query (median is reported)")
    args = parser.parse_args()

    settings = load_settings()
    queries = load_queries(QUERIES_PATH)
    names = index_names(INDEXES_PATH)

    conn = psycopg2.connect(**settings.pg_connect_kwargs(), application_name="benchmark_queries")
    conn.autocommit = True  # VACUUM cannot run inside a transaction
    try:
        with conn.cursor() as cur:
            cur.execute("SET search_path = public, etl")
            cur.execute("SHOW server_version")
            server_version = "PostgreSQL " + cur.fetchone()[0]
            cur.execute("SELECT count(*) FROM bookings")
            row_count = cur.fetchone()[0]

            print(f"Dropping {len(names)} indexes and measuring {len(queries)} queries ({args.runs} runs each)...")
            for name in names:
                cur.execute(f"DROP INDEX IF EXISTS {name}")
            before = run_all(cur, queries, args.runs)

            print("Creating indexes from sql/indexes.sql and measuring again...")
            cur.execute(INDEXES_PATH.read_text(encoding="utf-8"))
            after = run_all(cur, queries, args.runs)
            sizes = index_sizes(cur, names)
    finally:
        conn.close()

    print()
    print("\n".join(results_table(before, after)))
    print()
    for name, size in sizes.items():
        print(f"  {name:<45} {size}")
    write_report(before, after, sizes, queries, args.runs, server_version, row_count)
    print(f"\nReport written to {REPORT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
